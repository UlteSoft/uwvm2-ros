#!/usr/bin/env python3
"""Export actual VTune Microarchitecture instruction samples for known output hot paths.

Assembly is generated by VTune from the profiled image, with hardware cycle and
instruction attribution. Samples may skid and multiplexed estimates are not
exact instruction latency. Unresolved guest JIT code remains unqualified.
"""
import argparse
import csv
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[2]
GATE=Path('/sys/fs/cgroup/system.slice/docker-af71cb24aa7993383f76ad9c06750b17eb66fd090a2c9ba64b544b19cda9c913.scope')
def sha(path):
    with Path(path).open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile',type=Path,required=True);parser.add_argument('--runtime',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True);parser.add_argument('--vtune',default='/opt/intel/oneapi/vtune/latest/bin64/vtune');args=parser.parse_args()
    assert Path('/proc/self/cgroup').read_text().strip()=='0::/'+str(GATE.relative_to('/sys/fs/cgroup'))
    assert (GATE/'memory.max').read_text().strip()=='68719476736' and (GATE/'memory.swap.max').read_text().strip()=='0'
    assert os.sched_getaffinity(0).issubset(set(range(8,16)))
    profile=args.profile.resolve();runtime=args.runtime.resolve();out=args.output.resolve()
    assert out.is_relative_to((ROOT.parent/'uwvm2-ros-sdk/.tmp').resolve());out.mkdir(parents=True,exist_ok=False)
    receipt=json.loads((profile/'profile.json').read_text());assert receipt['complete'] and receipt['runtime_sha256']==sha(runtime)
    report_file=profile/'report-wasm-uarch-exploration-hotspots.stdout'
    functions=list(csv.DictReader(io.StringIO(report_file.read_text()),delimiter='\t'))
    record=dict(complete=False,scope=__doc__,profile_sha256=sha(profile/'profile.json'),runtime_sha256=sha(runtime),
        report_sha256=sha(report_file),vtune_sha256=sha(args.vtune),runner_sha256=sha(__file__),commands=[],functions={},
        cgroup=str(GATE),inode=GATE.stat().st_ino,memory_max=68719476736,swap_max=0,events_before=(GATE/'memory.events').read_text(),
        guest_jit_assembly_qualified=False)
    def save():(out/'results.json').write_text(json.dumps(record,indent=2)+'\n')
    selectors={'output_bound':'scene::outputs::registry::request_size(', 'output_mutation':'scene::outputs::registry::mutate(',
        'deployment_activation':'scene::deployment::activate(', 'memory_descriptor':'try_build_preload_memory_descriptor(',
        'authority':'scene::authority::admit_checked<(bool)1>(', 'process_identity':'__getpid'}
    for name,fragment in selectors.items():
        candidates=[row for row in functions if fragment in row['Function (Full)']]
        assert len(candidates)==1,(name,len(candidates));selected=candidates[0]
        argv=[args.vtune,'-report','hotspots','-result-dir',str(profile/'vtune-wasm-uarch-exploration'),
            '-source-object','function='+selected['Function'],'-group-by','address','-format','csv',
            '-column','Assembly,Source Line,Clockticks,Instructions Retired,CPI Rate,Machine Clears,Serializing Operations,Front-End Bound,Back-End Bound']
        result=subprocess.run(argv,capture_output=True,text=True,timeout=90)
        target=out/(name+'.tsv');target.write_text(result.stdout);(out/(name+'.stderr')).write_text(result.stderr)
        record['commands'].append(dict(argv=argv,exit=result.returncode));save();assert result.returncode==0,(name,result.stderr)
        reader=csv.DictReader(io.StringIO(result.stdout),delimiter='\t');columns=reader.fieldnames
        assert columns and all(field in columns for field in ('Address','Assembly','Source Line','Clockticks','Instructions Retired')),(name,columns)
        rows=[row for row in reader if row['Address'] and row['Assembly']]
        assert rows,(name,'No disassembly from the profiled image')
        def number(row,field):return float(row.get(field) or 0)
        sampled=[row for row in rows if number(row,'Clockticks') or number(row,'Instructions Retired')]
        entry=dict(function=selected['Function (Full)'],module=selected['Module'],function_start=selected['Start Address'],
            path=str(target),sha256=sha(target),instruction_rows=len(rows),sampled_rows=len(sampled),
            sampled_clockticks=sum(number(row,'Clockticks') for row in rows),
            sampled_instructions=sum(number(row,'Instructions Retired') for row in rows),
            sampled_assembly_qualified=bool(sampled),top_sampled_instructions=sorted(sampled,key=lambda row:number(row,'Clockticks'),reverse=True)[:8])
        record['functions'][name]=entry;save();print('PASS '+name+' instructions='+str(len(rows))+' sampled='+str(len(sampled)),flush=True)
    assert any(entry['sampled_assembly_qualified'] for entry in record['functions'].values())
    assert sha(runtime)==record['runtime_sha256'] and sha(profile/'profile.json')==record['profile_sha256'] and sha(report_file)==record['report_sha256']
    record['events_after']=(GATE/'memory.events').read_text();record['complete']=True;save()
if __name__=='__main__':main()
