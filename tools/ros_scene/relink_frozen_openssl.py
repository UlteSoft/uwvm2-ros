#!/usr/bin/env python3
"""Replace a frozen VM's identical-header OpenSSL archives with qualified O3/g builds.

Re-link the original objects and libraries first and require the exact original
binary digest. This proves the reused link inputs reproduce the qualified VM.
No C++ source is recompiled; the receipt distinguishes reused units from links.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import time
from performance_build_policy import compile_policy


def sha(p):
    with Path(p).open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()


def header_tokens_unchanged(left,right):
    if left==right:return True
    a,b=left.splitlines(keepends=True),right.splitlines(keepends=True)
    # Upstream embeds its relative input path in line 3 of an opening comment.
    # Only that path-only generator line may differ; preserve every other byte
    # and line position, including macros, declarations and configuration.
    allowed=rb' \* Generated by (?:Makefile|configdata\.pm) from [A-Za-z0-9_./, -]+\n'
    return (len(a)==len(b) and len(a)>=4 and a[0] in (b'/*\n',b'/*-\n')
        and a[:2]==b[:2] and a[3:]==b[3:] and a[1]==b' * WARNING: do not edit!\n'
        and bool(re.fullmatch(allowed,a[2])) and bool(re.fullmatch(allowed,b[2])))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ('baseline','openssl','output'):parser.add_argument('--'+name,type=Path,required=True)
    a=parser.parse_args()
    for k,v in vars(a).items():setattr(a,k,v.resolve())
    group=Path('/sys/fs/cgroup/system.slice/docker-af71cb24aa7993383f76ad9c06750b17eb66fd090a2c9ba64b544b19cda9c913.scope')
    assert Path('/proc/self/cgroup').read_text().strip()=='0::/'+str(group.relative_to('/sys/fs/cgroup'))
    assert (group/'memory.max').read_text().strip()=='68719476736' and (group/'memory.swap.max').read_text().strip()=='0'
    assert '.tmp' in a.output.parts;a.output.mkdir(parents=True,exist_ok=False)
    base_path=a.baseline/'full-build-results.json';base=json.loads(base_path.read_text())
    assert base['complete'] and base['sources_unchanged'] and sha(a.baseline/'uwvm2-ros')==base['binary_sha256']
    source=Path(base['source_root']);manifest=Path(base['full_source_manifest'])
    assert sha(manifest)==base['full_source_manifest_sha256']
    files=json.loads(manifest.read_text());assert all(sha(source/k)==v for k,v in files.items())
    dependency_path=a.openssl/'receipt.json';dependency=json.loads(dependency_path.read_text())
    policy=compile_policy(dependency['identity']['spec']['cflags'])
    assert all(sha(a.openssl/k)==v for k,v in dependency['artifacts'].items())
    link_path=a.baseline/'link.argv.json';link=json.loads(link_path.read_text())
    old_crypto=Path(next(x for x in link if x.endswith('/libcrypto.a'))).parent
    headers={str(p.relative_to(old_crypto)):sha(p) for p in (old_crypto/'include').rglob('*.h')}
    newer={str(p.relative_to(a.openssl)):sha(p) for p in (a.openssl/'include').rglob('*.h')}
    assert headers and headers.keys()==newer.keys(),'Header changes require recompilation'
    comment_changes=[]
    for name in headers:
        assert header_tokens_unchanged((old_crypto/name).read_bytes(),(a.openssl/name).read_bytes()),'Header changes require recompilation: '+name
        if headers[name]!=newer[name]:comment_changes.append(dict(path=name,old_sha256=headers[name],new_sha256=newer[name]))
    inputs={str(p):sha(p) for p in [base_path,link_path,manifest,dependency_path,Path(__file__).resolve()]}
    for item in link:
        if Path(item).is_file() and item!=str(a.baseline/'uwvm2-ros'):inputs[item]=sha(item)
    for k,v in dependency['artifacts'].items():inputs[str(a.openssl/k)]=v
    report=dict(complete=False,scope=__doc__,optimization='O3',debug='full -g',cgroup=str(group),memory_max=68719476736,swap_max=0,
        source_root=str(source),full_source_manifest=str(manifest),full_source_manifest_sha256=sha(manifest),sources=files,full_source_files=len(files),
        baseline_receipt=str(base_path),baseline_binary_sha256=base['binary_sha256'],dependency_receipt=str(dependency_path),dependency_build_policy=policy,
        reused_compilation=True,dependency_header_tokens_unchanged=True,generated_header_comment_changes=comment_changes,inputs=inputs,units=[],commands=[],events_before=(group/'memory.events').read_text(),affinity=sorted(os.sched_getaffinity(0)))
    receipt=a.output/'full-build-results.json'
    def save():receipt.write_text(json.dumps(report,indent=2)+'\n')
    def run(name,argv):
        start=time.monotonic();(a.output/(name+'.argv.json')).write_text(json.dumps(argv,indent=2)+'\n');save()
        with (a.output/(name+'.log')).open('wb') as log:r=subprocess.run(argv,stdout=log,stderr=subprocess.STDOUT,timeout=180)
        report['commands'].append(dict(name=name,argv=argv,exit=r.returncode,seconds=time.monotonic()-start));save();assert r.returncode==0,name
        print(name,'passed',flush=True)
    original=link.copy();original[original.index('-o')+1]=str(a.output/'baseline-reproduced')
    run('baseline-reproduce',original)
    report['baseline_reproduced']=sha(a.output/'baseline-reproduced')==base['binary_sha256'];save();assert report['baseline_reproduced']
    for name in ('main.default.cpp.o','uwvm_runtime.default.cpp.o','host_api.default.cpp.o'):
        args_path=a.baseline/(name+'.argv.json');args=json.loads(args_path.read_text());compile_policy(args)
        report['inputs'][str(args_path)]=sha(args_path)
        shutil.copyfile(a.baseline/name,a.output/name)
        recipe=[x.replace(str(a.baseline),str(a.output)) for x in args]
        (a.output/(name+'.argv.json')).write_text(json.dumps(recipe,indent=2)+'\n')
        report['units'].append(dict(unit=name,reused=True,baseline_argv=str(args_path),sha256=sha(a.output/name)))
    changed=[x.replace(str(a.baseline),str(a.output)).replace(str(old_crypto),str(a.openssl)) for x in link]
    run('link',changed)
    binary=a.output/'uwvm2-ros';report['binary_sha256']=sha(binary);report['link_returncode']=0
    sections=subprocess.check_output(['/usr/bin/readelf','--sections','--wide',str(binary)],text=True,timeout=30)
    assert '.debug_info' in sections and '.debug_line' in sections
    (a.output/'debug-sections.txt').write_text(sections)
    report['sources_unchanged']=report['full_source_unchanged']=all(sha(source/k)==v for k,v in files.items())
    report['inputs_unchanged']=all(sha(k)==v for k,v in report['inputs'].items())
    report['events_after']=(group/'memory.events').read_text()
    report['complete']=report['sources_unchanged'] and report['inputs_unchanged'];save();assert report['complete']


if __name__=='__main__':main()
