#!/usr/bin/env python3
"""Read frozen CPython and Core Wasm evidence as inert bytes only.

This module is called by the adjacent telemetry evidence reader. It never
imports the frozen SDK or application, unmarshals code objects, starts a
process, or executes a compiler, interpreter product, Wasm, or native ROS node.
Source and bytecode correspondence is checked independently from the builder.
"""
import hashlib
import json
from pathlib import Path
import re


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def verify_product(root, original, directory, producer, artifact, core):
    def owned(path):
        return root / Path(path).relative_to(original)

    def checked(row):
        path = owned(row['path'])
        assert path.stat().st_size == row['bytes'] and sha(path) == row['sha256']
        return path

    assert producer['runtime_model'] == 'CPython interpreter inside Wasm; no host Python application'
    assert producer['default_authority'] == [] and producer['source_and_tool_inputs_preserved'] is True
    checked(producer['builder'])
    for row in producer['tools'] + producer['compile_dependencies']:
        # The validator is an explicitly admitted external compiler tool.
        # Restored evidence can only recheck files retained inside this tree.
        if Path(row['path']).is_relative_to(original):
            checked(row)
    manifest = json.loads(checked(producer['frozen_assets']).read_bytes())
    assert manifest['external_runtime_assets'] == []
    assert manifest['runtime_or_native_ROS_cases_executed'] == 0
    assert manifest['producer'].startswith('3.14.8 ')
    modules = manifest['modules']
    assert len({row['name'] for row in modules}) == len(modules)
    assert {'roswasm_app', 'roswasm', 'roswasm.codecs', 'rclpy', 'std_msgs.msg'} <= {row['name'] for row in modules}
    assert sum(row['bytecode_bytes'] for row in modules) == manifest['total_bytecode_bytes'] <= 32 << 20
    for row in modules:
        path = owned(row['source'])
        assert path.stat().st_size == row['source_bytes'] and sha(path) == row['source_sha256']
        expected = '/__roswasm_frozen__/' + row['name'].replace('.', '/')
        expected += '/__init__.py' if row['package'] else '.py'
        assert row['virtual_filename'] == expected
    header = directory / 'frozen/roswasm_frozen.h'
    assert sha(header) == manifest['header_sha256']
    # Parse one bounded generated line at a time. Bytecode remains opaque data;
    # no marshal decoder or target-version code-object constructor is used.
    with header.open() as stream:
        assert stream.readline() == '/* Generated by matching native CPython3.14.8. Original sources are recorded in frozen-assets.json. */\n'
        for index, row in enumerate(modules):
            assert stream.readline() == 'static const unsigned char roswasm_code_' + str(index) + '[] = {\n'
            digest, length = hashlib.sha256(), 0
            while True:
                line = stream.readline(256)
                assert line
                if line == '};\n':
                    break
                assert re.fullmatch(r'(?:[0-9]{1,3},){1,24}\n', line)
                data = bytes(int(value) for value in line[:-2].split(','))
                digest.update(data)
                length += len(data)
            assert length == row['bytecode_bytes'] and digest.hexdigest() == row['bytecode_sha256']
        assert stream.readline() == 'static const struct _frozen roswasm_frozen[] = {\n'
        for index, row in enumerate(modules):
            symbol = 'roswasm_code_' + str(index)
            assert stream.readline() == '{"' + row['name'] + '",' + symbol + ',sizeof(' + symbol + '),' + str(int(row['package'])) + '},\n'
        assert stream.read() == '{NULL,NULL,0,0}\n};\n'

    retained = checked(producer['retained']).read_bytes()
    reader = core.Reader(retained)
    assert reader.take(8) == b'\0asm\x01\0\0\0'
    preserved, custom = [retained[:8]], 0
    while reader.at < len(retained):
        begin, kind = reader.at, reader.byte()
        reader.take(reader.uint())
        if kind:
            preserved.append(retained[begin:reader.at])
        else:
            custom += 1
    assert custom == producer['custom_sections_removed'] and custom > 0
    binary = artifact.read_bytes()
    assert b''.join(preserved) == binary, 'only complete custom sections may differ'
    reader = core.Reader(binary)
    reader.take(8)
    memories, exports = [], []
    while reader.at < len(binary):
        kind = reader.byte()
        part = core.Reader(reader.take(reader.uint()))
        assert kind not in (0, 8), 'baseline has no custom or implicit start section'
        if kind == 5:
            assert part.uint() == 1 and part.byte() == 1
            memories.append((part.uint(), part.uint()))
            assert part.at == len(part.body)
        elif kind == 7:
            for _ in range(part.uint()):
                exports.append((part.name(), part.byte(), part.uint()))
            assert part.at == len(part.body)
    assert len(memories) == 1 and 0 < memories[0][0] <= memories[0][1] == 4096
    assert ('memory', 2, 0) in exports and any(name == '_start' and kind == 0 for name, kind, _ in exports)
    # Recheck the fresh toolchain receipt and its immutable product identities.
    receipt = json.loads((root / 'out/toolchain-rebuild-results.json').read_bytes())
    assert receipt['status'] == 'FRESH_CPYTHON_3148_NATIVE_WASI_TOOLCHAIN_BUILT_NO_ROS_EXECUTED'
    assert receipt['make_jobs'] == 1 and receipt['source_and_archive_inputs_preserved'] is True
    assert len(receipt['commands']) == 6
    for command in receipt['commands']:
        assert command['exit'] == 0 and command['forced_signal'] is None
        for stream in ('stdout', 'stderr'):
            path = root / 'out/commands' / command['label'] / stream
            assert sha(path) == command[stream + '_sha256']
    products = json.loads((root / 'out/toolchain-products.json').read_bytes())
    for row in products['files']:
        checked(row)
    return {'frozen_modules': len(modules), 'frozen_bytecode_bytes': manifest['total_bytecode_bytes'],
            'memory_pages': memories, 'custom_sections_removed': custom,
            'scope': 'Inert source/header/opaque-bytecode/Core-section/toolchain correspondence'}
