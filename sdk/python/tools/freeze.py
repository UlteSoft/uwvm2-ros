#!/usr/bin/env python3
"""Freeze a real CPython3.14.8 stdlib/ROS SDK/entry bundle without preopens.

Run with the producer's matching native build-Python on Linux, never host Python
of a different bytecode version. This compiles Python code objects into data for
the target interpreter, not into native application functions. The manifest
retains every original source and bytecode hash. Freezing pure Python modules
does not make unavailable WASI C extensions, threads, sockets or subprocesses
work. Actual guest startup and required builtin operations must still be tested.
"""
import argparse
import hashlib
import json
import marshal
from pathlib import Path
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stdlib', type=Path, required=True)
    parser.add_argument('--sdk-python', type=Path, required=True)
    parser.add_argument('--entry', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    if sys.version_info[:3] != (3, 14, 8) or sys.platform != 'linux':
        raise RuntimeError('use the matching pinned native CPython3.14.8 on Linux')
    args.out.mkdir(parents=True, exist_ok=False)
    modules = {}

    def collect(root, excluded, prefix=()):
        for path in sorted(root.rglob('*.py')):
            relative = path.relative_to(root)
            if any(part in excluded for part in relative.parts):
                continue
            parts = [*prefix, *relative.with_suffix('').parts]
            package = parts[-1] == '__init__'
            if package:
                parts.pop()
            if not parts or not all(part.isidentifier() for part in parts):
                continue
            name = '.'.join(parts)
            if name in modules:
                raise ValueError('duplicate frozen module: ' + name)
            modules[name] = path, package

    collect(args.stdlib.resolve(strict=True), {'test', 'tests', 'idlelib', 'tkinter',
                                             'turtledemo', 'ensurepip', 'venv', '__pycache__'})
    # Preserve package names by collecting from explicit parent roots. Never
    # accidentally freeze SDK build/test tools as application modules.
    sdk = args.sdk_python.resolve(strict=True)
    for path in sorted((sdk / 'roswasm').rglob('*.py')):
        relative = path.relative_to(sdk).with_suffix('')
        parts = list(relative.parts); package = parts[-1] == '__init__'
        if package: parts.pop()
        name = '.'.join(parts)
        if name in modules: raise ValueError('duplicate SDK/stdlib module: ' + name)
        modules[name] = path, package
    # Select actual import packages, rather than making every preserved
    # example/upstream audit file under the compatibility directory importable.
    # Prefixing each package retains identical module and virtual-file names.
    # A user application is selected only by the explicit --entry below.
    compatibility_packages = ('rclpy', 'std_msgs', 'example_interfaces',
                              'std_srvs', 'examples_rclpy_minimal_service')
    for package_name in compatibility_packages:
        collect(sdk / 'compat/rclpy' / package_name, set(), (package_name,))
    if 'roswasm_app' in modules:
        raise ValueError('reserved frozen entry name')
    modules['roswasm_app'] = args.entry.resolve(strict=True), False
    header = args.out / 'roswasm_frozen.h'
    rows, entries, total = [], [], 0
    with header.open('x') as stream:
        stream.write('/* Generated by matching native CPython3.14.8. Original sources are recorded in frozen-assets.json. */\n')
        for index, (name, (path, package)) in enumerate(sorted(modules.items())):
            source = path.read_bytes()
            if len(source) > 2 << 20:
                raise ValueError('individual Python source bound')
            filename = '/__roswasm_frozen__/' + name.replace('.', '/') + (('/__init__' if package else '') + '.py')
            bytecode = marshal.dumps(compile(source, filename, 'exec', dont_inherit=True, optimize=0))
            total += len(bytecode)
            if total > 32 << 20:
                raise ValueError('total frozen bytecode bound')
            symbol = f'roswasm_code_{index}'
            stream.write(f'static const unsigned char {symbol}[] = {{\n')
            for offset in range(0, len(bytecode), 24):
                stream.write(','.join(str(value) for value in bytecode[offset:offset + 24]) + ',\n')
            stream.write('};\n')
            entries.append(f'{{"{name}",{symbol},sizeof({symbol}),{int(package)}}},\n')
            rows.append({'name': name, 'source': str(path), 'source_bytes': len(source),
                         'source_sha256': hashlib.sha256(source).hexdigest(),
                         'bytecode_bytes': len(bytecode), 'bytecode_sha256': hashlib.sha256(bytecode).hexdigest(),
                         'package': package, 'virtual_filename': filename})
        stream.write('static const struct _frozen roswasm_frozen[] = {\n')
        stream.writelines(entries)
        stream.write('{NULL,NULL,0,0}\n};\n')
    report = {'producer': sys.version, 'native_build_python': sys.executable,
              'modules': rows, 'total_bytecode_bytes': total,
              'compatibility_package_roots': list(compatibility_packages),
              'header_sha256': hashlib.sha256(header.read_bytes()).hexdigest(),
              'external_runtime_assets': [], 'stdlib_C_builtin_qualification': 'REQUIRED',
              'runtime_or_native_ROS_cases_executed': 0}
    (args.out / 'frozen-assets.json').write_text(json.dumps(report, indent=2) + '\n')


if __name__ == '__main__':
    main()
